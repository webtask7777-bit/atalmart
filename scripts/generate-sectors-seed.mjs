// Great-circle distance from the dark store (m).
function distanceM(a, b) {
  const R = 6371e3, toR = (x) => (x * Math.PI) / 180;
  const dLat = toR(b.lat - a.lat), dLng = toR(b.lng - a.lng);
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(toR(a.lat)) * Math.cos(toR(b.lat)) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
}

// ETA bands by straight-line distance from the store — e-scooter through
// planned-city roads. Tuned from the owner's current zones (27/29 = 15–20,
// 21–28 = 25–30).
export function etaForDistance(m) {
  if (m < 1200) return { min: 15, max: 20, zone: "Immediate" };
  if (m < 2500) return { min: 20, max: 25, zone: "Near" };
  if (m < 4500) return { min: 25, max: 30, zone: "Medium" };
  if (m < 6500) return { min: 35, max: 45, zone: "Far" };
  return { min: 45, max: 60, zone: "Outer" };
}

const slugify = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

function polyWkt({ lat, lng, half }) {
  const dLat = half / 110_900, dLng = half / 103_700;
  const ring = [[lng - dLng, lat - dLat], [lng + dLng, lat - dLat], [lng + dLng, lat + dLat], [lng - dLng, lat + dLat], [lng - dLng, lat - dLat]];
  return `POLYGON((${ring.map(([x, y]) => `${x.toFixed(7)} ${y.toFixed(7)}`).join(", ")}))`;
}

